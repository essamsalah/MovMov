"""Build classic browser scripts so games also start from file:// URLs.

No external build dependencies. Only the named modules below are bundled.
Run from any directory: python3 tools/build_browser.py [--check]
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
BUNDLES = {
    'space-explorer.browser.js': ['space-pose.js', 'space-explorer.js'],
    'mini-games.browser.js': [
        'space-pose.js', 'mini-rules.js', 'motion-camera.js', 'mini-games.js'
    ],
}


def bundle(names):
    parts = ['// Generated by tools/build_browser.py; edit the source modules instead.\n',
             "(() => {\n'use strict';\n"]
    loaded = set()
    for name in names:
        source = (ROOT / 'js' / name).read_text()
        def remove_import(match):
            dependency = match.group(1)
            if dependency != './' + Path(dependency).name or Path(dependency).name not in loaded:
                raise ValueError(f'{name}: dependency {dependency} is not earlier in the bundle')
            return ''
        source = re.sub(r"^import\s+\{[^\n]+\}\s+from\s+['\"]([^'\"]+)['\"];?\s*\n", remove_import, source, flags=re.M)
        source = re.sub(r'^export (?=(?:const|let|function|class)\b)', '', source, flags=re.M)
        if re.search(r'^\s*(?:import\s|export\s)', source, flags=re.M):
            raise ValueError(f'{name}: unsupported module declaration')
        parts.append(f'\n// Source: js/{name}\n{source}\n')
        loaded.add(name)
    parts.append('})();\n')
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if browser scripts need rebuilding')
    args = parser.parse_args()
    for name, modules in BUNDLES.items():
        output = ROOT / 'js' / name
        expected = bundle(modules)
        if args.check:
            if not output.exists() or output.read_text() != expected:
                raise SystemExit(f'{name} is stale; run python3 tools/build_browser.py')
        else:
            output.write_text(expected)
        print(('Checked ' if args.check else 'Built ') + name)


if __name__ == '__main__':
    main()
